import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import {STEPS,normalizePlan,summarizePlan,exportPlan} from '../src/review/review-domain.mjs';
import {loadPlan,savePlan,PLAN_KEY} from '../src/review/review-storage.mjs';

const values=new Map(),storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value)};
assert.equal(loadPlan(storage).savedAt,null);
assert.equal(values.size,0,'abrir não deve gravar um plano vazio');
const plan=normalizePlan();
assert.deepEqual(summarizePlan(plan),{now:0,later:0,undecided:7});
plan.product='Oferta de teste em memória';
plan.steps.offer={decision:'now',notes:'Desconto confirmado manualmente.'};
const first=savePlan(storage,plan,{now:()=> '2026-10-25T12:00:00.000Z'});
assert.deepEqual(loadPlan(storage).plan,plan);
assert.equal(savePlan(storage,plan,{expectedSavedAt:first}),first,'salvar sem mudanças é idempotente');
assert.equal(JSON.parse(values.get(PLAN_KEY)).length,1);
const secondPlan=normalizePlan(plan);secondPlan.steps.materials.decision='later';
const second=savePlan(storage,secondPlan,{expectedSavedAt:first,now:()=> '2026-10-25T12:01:00.000Z'});
assert.equal(JSON.parse(values.get(PLAN_KEY)).length,2,'revisões anteriores são preservadas');
assert.equal(JSON.parse(values.get(PLAN_KEY))[0].plan.steps.materials.decision,'undecided');
assert.throws(()=>savePlan(storage,plan,{expectedSavedAt:first}),/outra aba/);
assert.equal(loadPlan(storage).savedAt,second);
assert.deepEqual(summarizePlan(secondPlan),{now:1,later:1,undecided:5});
const exported=exportPlan(secondPlan);
for(const step of STEPS)assert.ok(exported.includes(step.title));
assert.ok(exported.includes('Desconto confirmado manualmente.'));
assert.ok(exported.includes('Implementar agora'));
const imagesStep=STEPS.find(step=>step.id==='images');assert.ok(imagesStep.outputs.some(item=>item.includes('Pendências específicas')));assert.ok(!imagesStep.outputs.some(item=>item.includes('Briefs das peças')));
const malformed='{"dados":"preservar"}';values.set(PLAN_KEY,malformed);
assert.throws(()=>loadPlan(storage));assert.throws(()=>savePlan(storage,plan));assert.equal(values.get(PLAN_KEY),malformed);
const normalized=normalizePlan({steps:{offer:{decision:'constructor'},unknown:{decision:'now'}}});
assert.equal(normalized.steps.offer.decision,'undecided');assert.equal(Object.keys(normalized.steps).length,7);

const registry=await readFile(new URL('../src/view-registry.js',import.meta.url),'utf8');
const context=vm.createContext({window:{},URLSearchParams,encodeURIComponent});vm.runInContext(registry,context);
assert.equal(context.window.PanelViews.resolveRoute('/?view=review').id,'review');
assert.equal(context.window.PanelViews.urlFor('review'),'/?view=review');
assert.equal(context.window.PanelViews.definition('review').navId,'reviewNav');
for(const file of ['review-domain.mjs','review-view.mjs','review-storage.mjs','review.css'])assert.equal(await readFile(new URL('../src/review/'+file,import.meta.url),'utf8'),await readFile(new URL('../dist/review/'+file,import.meta.url),'utf8'));
console.log('review: plano, histórico, conflitos, exportação, rota e build ok');
