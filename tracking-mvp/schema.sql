CREATE TABLE IF NOT EXISTS tracking_events (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    event_id CHAR(36) NOT NULL,
    event_type VARCHAR(32) NOT NULL,
    click_id CHAR(36) NULL,
    clickbank_extclid VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NULL,
    product_key VARCHAR(253) CHARACTER SET ascii COLLATE ascii_bin NULL,
    presell_host VARCHAR(253) CHARACTER SET ascii COLLATE ascii_bin NULL,
    visitor_id CHAR(36) NOT NULL,
    gclid VARCHAR(2048) NULL,
    gbraid VARCHAR(2048) NULL,
    wbraid VARCHAR(2048) NULL,
    utm_source VARCHAR(255) NULL,
    utm_medium VARCHAR(255) NULL,
    utm_campaign VARCHAR(255) NULL,
    utm_term VARCHAR(255) NULL,
    utm_content VARCHAR(255) NULL,
    page_url VARCHAR(2048) NOT NULL,
    referrer_origin VARCHAR(512) NULL,
    destination_url VARCHAR(2048) NULL,
    received_at_utc DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uq_tracking_events_event_id (event_id),
    KEY idx_tracking_events_click_id (click_id),
    KEY idx_tracking_events_clickbank_extclid (clickbank_extclid),
    KEY idx_tracking_events_product_key (product_key),
    KEY idx_tracking_events_presell_host (presell_host),
    KEY idx_tracking_events_visitor_id (visitor_id),
    KEY idx_tracking_events_received_at (received_at_utc)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
